#!/usr/bin/env python3
"""Build, validate, and evaluate the skills lifecycle graph.

  python3 lifecycle/build.py           validate graph.yaml, regenerate every derived file
  python3 lifecycle/build.py --check   validate + fail if any derived file is stale (CI)
  python3 lifecycle/build.py eval      run routing evals (lifecycle/evals/routing.yaml)

Derived files (never edit by hand):
  skills/lifecycle-router/references/registry.json   router runtime data
  agents/<phase>.md                                   Claude Code phase subagents
  skills/*/SKILL.md  (<!-- lifecycle:begin/end -->)   per-skill "Lifecycle" section
  docs/lifecycle.md                                   human-readable graph
  docs/lifecycle.html                                 interactive lifecycle map (GitHub Pages)
  README.md  (<!-- lifecycle-diagram:begin/end -->)   Mermaid overview + per-phase diagrams
  lifecycle/bundles.txt                               installer bundles

Needs PyYAML at build time only (`pip install pyyaml`); the router itself is stdlib.
"""
